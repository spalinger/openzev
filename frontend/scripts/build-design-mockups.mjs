import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'
import { build } from 'vite'
import react from '@vitejs/plugin-react'

const frontend = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const output = path.resolve(frontend, '../design/mockups')
const temporaryBuild = path.resolve(frontend, 'node_modules/.tmp/design-mockups')

// An isolated build keeps the prototype free of product providers and chunks.
await build({
  configFile: false,
  root: frontend,
  plugins: [react()],
  build: {
    outDir: temporaryBuild,
    emptyOutDir: true,
    cssCodeSplit: false,
    rolldownOptions: {
      input: path.resolve(frontend, 'design-lab.html'),
      output: { codeSplitting: false },
    },
  },
})

let html = await readFile(path.join(temporaryBuild, 'design-lab.html'), 'utf8')
const script = html.match(/<script[^>]*src="([^"]+)"[^>]*><\/script>/)
if (!script) throw new Error('Prototype build did not produce a script entry.')
const javascript = await readFile(path.join(temporaryBuild, script[1].replace(/^\//, '')), 'utf8')
// A replacer function preserves literal $&, $' and $` in bundled JavaScript.
html = html.replace(script[0], () => `<script type="module">${javascript.replace(/<\/script/gi, '<\\/script')}</script>`)

for (const stylesheet of [...html.matchAll(/<link[^>]*rel="stylesheet"[^>]*href="([^"]+)"[^>]*>/g)]) {
  let css = await readFile(path.join(temporaryBuild, stylesheet[1].replace(/^\//, '')), 'utf8')
  for (const asset of [...css.matchAll(/url\(([^)]+)\)/g)]) {
    const url = asset[1].replace(/^['"]|['"]$/g, '')
    if (url.startsWith('data:')) continue
    const bytes = await readFile(path.join(temporaryBuild, url.replace(/^\//, '')))
    const mime = url.endsWith('.woff2') ? 'font/woff2' : 'application/octet-stream'
    css = css.replace(asset[0], `url(data:${mime};base64,${bytes.toString('base64')})`)
  }
  html = html.replace(stylesheet[0], () => `<style>${css}</style>`)
}
html = html.replace(/\s*<link[^>]*rel="modulepreload"[^>]*>/g, '')
const favicon = await readFile(path.join(frontend, 'public/favicon.svg'))
html = html.replace('href="/favicon.svg"', `href="data:image/svg+xml;base64,${favicon.toString('base64')}"`)
html = html.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by npm run mockups:build. Edit frontend/src/design-lab, locale copy, and design/tokens.json. -->')

const inlinedScript = html.match(/<script type="module">([\s\S]*?)<\/script>/)?.[1]
if (!inlinedScript) throw new Error('Portable mockup is missing its inline script.')
const syntaxCheck = spawnSync(process.execPath, ['--input-type=module', '--check'], { input: inlinedScript, encoding: 'utf8' })
if (syntaxCheck.status !== 0) throw new Error(`Portable script failed syntax validation: ${syntaxCheck.stderr.slice(-2000)}`)

await mkdir(output, { recursive: true })
await writeFile(path.join(output, 'index.html'), html)
console.log(`\nPortable mockup: ${path.join(output, 'index.html')} (${Math.round(Buffer.byteLength(html) / 1024)} kB)`)
